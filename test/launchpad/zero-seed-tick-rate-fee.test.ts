import { describe, expect, test } from "bun:test";
import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import {
  DEFAULT_DECAY_RATE_X32, decayRateForHalfLife, feePercent, HALF_LIFE_X32_E30, halfLifeSeconds, MAX_CREATOR_FEE,
  MAX_DECAY_PRODUCT, MAX_TICK_MAGNITUDE, Q128, Q64, saturationElapsedSeconds, tickFactorQ128, tickRateDecayedFee,
  tickRateExcessHalvingTime, tickRateFeeAt, tickRatePhase,
} from "../../src/launchpad/zero-seed/fee.js";
import { resolveParameters, validateParameters } from "../../src/launchpad/zero-seed/installation.js";
import { pin, request, v1Pin } from "./zero-seed-fixture.js";

// tick_rate_v2 (evm-contracts 3d6378f). The outside oracle is the contracts' own vector file
// test/vectors/zero-seed-launch.json v7 (sha256 4c1245ca…66605), vendored verbatim: its fee rows, tables, tick steps,
// saturation seconds and SHA-256 digest chains come from the independent 150-digit Python oracle
// (zero-seed-launch-reference.py), pinned identically in Solidity. Nothing here is generated by this implementation.
const bytes = readFileSync(new URL("../fixtures/launchpad/zero-seed-launch-vectors-3d6378f.json", import.meta.url));
const v = JSON.parse(bytes.toString("utf8"));
const curve = v.fee_curve;
const RATES = curve.decay_rates_x32 as Record<string, string>;
const FEES = curve.rates_q64 as Record<string, string>;
const FINAL = BigInt(curve.final_fee_q64);
const UINT256_MAX = (1n << 256n) - 1n;
const magnitude = (rate: bigint, t: bigint) => (rate * t) >> 32n;
type Row = { t: string; fee_q64: string; tick_magnitude?: string };

describe("vector provenance", () => {
  test("the vendored file is the frozen v7 export of 3d6378f", () => {
    expect(createHash("sha256").update(bytes).digest("hex")).toBe("4c1245ca2b35d96ae9daa6c908acf35b5b3c316f0979520994513f9054766605");
    expect(v.version).toBe(7);
    expect(v.abi.LaunchParameters).toContain("uint64 tradingStart,uint64 decayRateX32,uint64 initialFee");
    expect(MAX_DECAY_PRODUCT).toBe(381061679028371455n);
    expect(MAX_TICK_MAGNITUDE).toBe(88722835n);
  });
});

describe("tick_rate_v2 fee math against the contract's v7 vectors", () => {
  test(`all ${v.fee.length} fee rows (5% -> 0.3% at the default and the 600 s rate, through uint256.max)`, () => {
    expect(v.fee).toHaveLength(40);
    const initial = BigInt(FEES["5"]);
    for (const row of v.fee as (Row & { decayRateX32: string; t_minus_start: string })[]) {
      const rate = BigInt(row.decayRateX32);
      const elapsed = BigInt(row.t_minus_start);
      const fee = elapsed < 0n
        ? tickRateFeeAt({ tradingStart: 1000n, decayRateX32: rate, initialFee: initial, finalFee: FINAL }, 1000n + elapsed)
        : tickRateDecayedFee(initial, FINAL, rate, elapsed);
      expect(fee.toString()).toBe(row.fee_q64);
      if (row.tick_magnitude !== null && row.tick_magnitude !== undefined) {
        expect(magnitude(rate, elapsed).toString()).toBe(row.tick_magnitude);
      }
    }
  });

  test("the five SHA-256 digest chains, every sampled second", () => {
    expect(curve.digests_sha256).toHaveLength(5);
    for (const d of curve.digests_sha256) {
      let h: Buffer = Buffer.alloc(32);
      const [initial, final, rate] = [BigInt(d.initialFee), BigInt(d.finalFee), BigInt(d.decayRateX32)];
      for (let t = 0n; t <= BigInt(d.last); t += BigInt(d.step)) {
        const word = Buffer.alloc(8);
        word.writeBigUInt64BE(tickRateDecayedFee(initial, final, rate, t));
        h = createHash("sha256").update(Buffer.concat([h, word])).digest();
      }
      expect(`${d.label}: ${h.toString("hex")}`).toBe(`${d.label}: ${d.digest}`);
    }
  });

  const TABLES: Record<string, [string, string, string]> = {
    "default_one_day_50_to_0.3": [FEES["50"], curve.final_fee_q64, RATES.default_one_day],
    "two_ticks_per_second_50_to_0.3": [FEES["50"], curve.final_fee_q64, RATES.two_ticks_per_second],
    "two_ticks_per_second_99.9_to_0": [FEES["99.9"], "0", RATES.two_ticks_per_second],
    default_one_day_max_to_0: [FEES.max, "0", RATES.default_one_day],
    min_rate_max_to_0: [FEES.max, "0", RATES.min],
  };
  for (const [name, [initial, final, rate]] of Object.entries(TABLES)) {
    test(`table ${name}`, () => {
      const rows = curve.tables[name] as Row[];
      expect(rows.length).toBeGreaterThan(5);
      for (const row of rows) {
        expect(tickRateDecayedFee(BigInt(initial), BigInt(final), BigInt(rate), BigInt(row.t)).toString()).toBe(row.fee_q64);
        if (row.tick_magnitude !== undefined) expect(magnitude(BigInt(rate), BigInt(row.t)).toString()).toBe(row.tick_magnitude);
      }
    });
  }

  test("fractional accumulation: tick steps at 1/4 and just under 1/10 tick per second, and 16 ticks per second", () => {
    const [quarter, tenth, perSecond, oneUnit] = curve.tick_steps;
    expect([quarter.decayRateX32, tenth.decayRateX32, perSecond.decayRateX32]).toEqual(["1073741824", "429496729", "68913100933"]);
    for (const step of [quarter, tenth, perSecond]) {
      for (const row of step.rows as Row[]) {
        expect(tickRateDecayedFee(BigInt(FEES["50"]), FINAL, BigInt(step.decayRateX32), BigInt(row.t)).toString()).toBe(row.fee_q64);
        expect(magnitude(BigInt(step.decayRateX32), BigInt(row.t)).toString()).toBe(row.tick_magnitude!);
      }
    }
    // The fee only moves when the accumulated magnitude crosses a whole tick: every 4 s at 1/4 tick/s, and the first
    // step only at 11 s at floor(0.1 * 2^32), whose fractional rate falls just short at 10 s.
    expect(magnitude(1073741824n, 3n)).toBe(0n);
    expect(magnitude(1073741824n, 4n)).toBe(1n);
    expect(magnitude(429496729n, 10n)).toBe(0n);
    expect(magnitude(429496729n, 11n)).toBe(1n);
    // A one-unit excess over the floor is floored away at the first whole tick.
    for (const row of oneUnit.rows as Row[]) {
      expect(tickRateDecayedFee(FINAL + 1n, FINAL, BigInt(oneUnit.decayRateX32), BigInt(row.t)).toString()).toBe(row.fee_q64);
    }
  });

  test("saturation: the last evaluated second per rate, then exactly finalFee through uint256.max", () => {
    const SAT = curve.saturation_second as Record<string, string>;
    for (const [key, second] of Object.entries(SAT)) {
      const rate = BigInt(key === "default_one_day" ? RATES.default_one_day : key === "600s" ? RATES["600s"]
        : RATES[key] ?? (key === "min" ? RATES.min : RATES.max));
      expect(saturationElapsedSeconds(rate)?.toString()).toBe(second);
      const s = BigInt(second);
      expect(tickRateDecayedFee(MAX_CREATOR_FEE, 0n, rate, s + 1n)).toBe(0n);
      expect(tickRateDecayedFee(MAX_CREATOR_FEE, 0n, rate, UINT256_MAX)).toBe(0n);
      // At the saturation second the helper is still called with a supported magnitude.
      expect(magnitude(rate, s) <= MAX_TICK_MAGNITUDE).toBe(true);
      expect(magnitude(rate, s + 1n) > MAX_TICK_MAGNITUDE || rate * (s + 1n) > MAX_DECAY_PRODUCT).toBe(true);
    }
    // A full-span excess leaves one raw unit at the minimum tick: the guard, not a clamp, gives finalFee.
    expect(tickRateDecayedFee(MAX_CREATOR_FEE, 0n, 1n, MAX_DECAY_PRODUCT)).toBe(1n);
    expect(tickRateDecayedFee(MAX_CREATOR_FEE, 0n, 1n, MAX_DECAY_PRODUCT + 1n)).toBe(0n);
    expect(saturationElapsedSeconds(0n)).toBeNull();
  });

  test("the compact tick factor: 2^128 at magnitude 0, bounded and strictly decreasing, refused outside the helper", () => {
    expect(tickFactorQ128(0n)).toBe(Q128);
    let previous = Q128;
    for (const m of [1n, 2n, 16n, 1n << 20n, 1386295n, 1n << 26n, MAX_TICK_MAGNITUDE]) {
      const factor = tickFactorQ128(m);
      expect(factor < previous).toBe(true);
      previous = factor;
    }
    expect(() => tickFactorQ128(MAX_TICK_MAGNITUDE + 1n)).toThrow("unsigned_domain");
    expect(() => tickFactorQ128(-1n)).toThrow("unsigned_domain");
  });

  test("rate 0 and an equal floor are flat; the phase follows the API v5 labels", () => {
    const flat = { tradingStart: 1000n, decayRateX32: 0n, initialFee: BigInt(FEES["50"]), finalFee: FINAL };
    expect(tickRateFeeAt(flat, UINT256_MAX)).toBe(BigInt(FEES["50"]));
    expect(tickRatePhase(flat, 999n)).toBe("before_trading_start");
    expect(tickRatePhase(flat, 1000n)).toBe("constant");
    const decaying = { ...flat, decayRateX32: DEFAULT_DECAY_RATE_X32 };
    expect(tickRatePhase(decaying, 1000n)).toBe("decaying");
    expect(tickRatePhase(decaying, 1000n + 5529597n)).toBe("at_floor");
    expect(tickRatePhase({ ...flat, finalFee: flat.initialFee }, 1000n)).toBe("at_floor");
    expect(() => tickRateFeeAt({ ...flat, finalFee: flat.initialFee + 1n }, 1000n)).toThrow("invalid_fee_schedule");
    expect(() => tickRateFeeAt({ ...flat, decayRateX32: Q64 }, 1000n)).toThrow("unsigned_domain");
    expect(tickRateExcessHalvingTime(flat)).toBeNull();
    expect(tickRateExcessHalvingTime(decaying)).toBe(86401n);
  });
});

describe("half-life <-> decayRateX32, exact integers only", () => {
  test("the normative constant and the pinned conversions (API, interface and contract)", () => {
    expect(HALF_LIFE_X32_E30).toBe(5954091920683119788732747343471285361579197626n);
    expect(DEFAULT_DECAY_RATE_X32.toString()).toBe(RATES.default_one_day);
    const pins: [string, string][] = [["86400", "68913100933"], ["600", "9923486534471"], ["3600", "1653914422411"],
      ["604800", "9844728704"], ["86400.5", "68912702133"]];
    for (const [seconds, rate] of pins) expect(decayRateForHalfLife(seconds).toString()).toBe(rate);
    expect(decayRateForHalfLife("600").toString()).toBe(RATES["600s"]);
  });

  test("rate -> half-life display: 6 floored decimals; 693147.527133 at 2 ticks/s (the vector note's 693151.5 is a typo)", () => {
    const display: [string, string | null][] = [["68913100933", "86400.000001"], ["9923486534471", "600.000000"],
      ["8589934592", "693147.527133"], ["1073741824", "5545180.217067"], ["1", "5954091920683119.788732"],
      ["18446744073709551615", "0.000322"], ["0", null]];
    for (const [rate, seconds] of display) expect(halfLifeSeconds(BigInt(rate))).toBe(seconds);
    // The note string reads 693151.52713347783; its own "8.0225408233 days" is 693147.527 s.
    expect(curve.half_life_s.two_ticks_per_second).toContain("8.0225408233 days");
    expect(Math.round(8.0225408233 * 86400)).toBe(693148);
  });

  test("integer seconds, milliseconds and microseconds are the same rational; every integer half-life to 10^6 s round-trips", () => {
    for (const seconds of [1n, 7n, 600n, 86400n, 999999n]) {
      const rate = decayRateForHalfLife(seconds.toString());
      expect(decayRateForHalfLife(`${seconds}.000`)).toBe(rate);
      expect(decayRateForHalfLife(`${seconds}.000000`)).toBe(rate);
      expect(rate).toBe(HALF_LIFE_X32_E30 / (seconds * 10n ** 30n));
    }
    // Whole seconds -> rate -> display: the display is never shorter than the request (the rate is floored) and keeps
    // its whole seconds; display -> rate gives back the same integer rate.
    for (let seconds = 1n; seconds <= 1_000_000n; seconds += 997n) {
      const rate = decayRateForHalfLife(seconds.toString());
      const shown = halfLifeSeconds(rate)!;
      expect(shown.split(".")[0]).toBe(seconds.toString());
      expect(decayRateForHalfLife(shown)).toBe(rate);
    }
  });

  test("rates round-trip exactly through the decimal string and through the 6-decimal display", () => {
    for (const rate of [1n, 2n, 429496729n, 1073741824n, 8589934592n, 68913100933n, 9923486534471n]) {
      expect(BigInt(rate.toString())).toBe(rate);
      expect(decayRateForHalfLife(halfLifeSeconds(rate)!)).toBe(rate);
    }
    // Near the top of uint64 the half-life is under a millisecond and the microsecond display is lossy: 2^64 - 1
    // shows 0.000322 s, whose exact rate would exceed uint64. The integer rate stays the source of truth.
    expect(halfLifeSeconds(Q64 - 1n)).toBe("0.000322");
    expect(() => decayRateForHalfLife("0.000322")).toThrow("invalid_half_life");
  });

  test("a half-life whose rate is 0 or above uint64 refuses with invalid_half_life; nothing is clamped", () => {
    for (const bad of ["0", "0.000000", "0.000322", "5954091920683120", "-1", "1e3", "1.0000001", " 1", ""]) {
      expect(() => decayRateForHalfLife(bad)).toThrow("invalid_half_life");
    }
    expect(decayRateForHalfLife("0.000323") < Q64).toBe(true);
    expect(decayRateForHalfLife("5954091920683119")).toBe(1n);
  });
});

describe("creation validation of tick_rate_v2 at the producer", () => {
  const base = request();
  type Vector = { initialFee: string; finalFee: string; decayRateX32: string; verdict: string };
  const vectors = v.creator_fee_range.vectors as Vector[];

  test(`the contract's ${vectors.length} accept/refuse verdicts, rate 0 and 2^64 - 1 included`, () => {
    expect(vectors).toHaveLength(13);
    for (const vector of vectors) {
      const run = () => validateParameters({ ...base, initialFee: vector.initialFee, finalFee: vector.finalFee,
        decayRateX32: vector.decayRateX32 }, pin);
      if (vector.verdict === "accept") expect(run).not.toThrow();
      else if (vector.verdict === "InvalidFeeSchedule") expect(run).toThrow("invalid_fee_schedule");
      else expect(run).toThrow(/must be at most 18446744073709551615/);
    }
    expect(vectors.filter((x) => x.verdict === "accept").map((x) => x.decayRateX32)).toEqual(expect.arrayContaining(["0", "18446744073709551615"]));
  });

  test("the maximum fee is just under 100%; a rising fee refuses; equal is flat", () => {
    expect(() => validateParameters({ ...base, initialFee: MAX_CREATOR_FEE.toString(), finalFee: MAX_CREATOR_FEE.toString() }, pin))
      .not.toThrow();
    expect(feePercent(MAX_CREATOR_FEE)).toBe("99.9999%");
    expect(() => validateParameters({ ...base, finalFee: (BigInt(base.initialFee) + 1n).toString() }, pin)).toThrow("invalid_fee_schedule");
    expect(() => validateParameters({ ...base, finalFee: base.initialFee }, pin)).not.toThrow();
  });

  test("non-canonical or out-of-range rates refuse; nothing is truncated or wrapped", () => {
    for (const bad of ["18446744073709551616", "01", "+1", "-1", " 1", "0x1", "1e3", "1.0", ""]) {
      expect(() => validateParameters({ ...base, decayRateX32: bad }, pin)).toThrow();
    }
    expect(() => validateParameters({ ...base, decayRateX32: 1 } as never, pin)).toThrow();
    expect(() => validateParameters({ ...base, feeDuration: 3600 } as never, pin)).toThrow();
  });

  test("a fixed_base_duration_v1 instance gets no create: unsupported_fee_model", () => {
    expect(() => validateParameters(base, v1Pin)).toThrow("unsupported_fee_model");
  });

  test("tool input: neither decay input is the one-day default; a half-life converts exactly", () => {
    const { decayRateX32: _rate, ...rest } = base;
    expect(resolveParameters(rest).decayRateX32).toBe("68913100933");
    expect(resolveParameters({ ...rest, halfLifeSeconds: "600" }).decayRateX32).toBe("9923486534471");
    expect(resolveParameters({ ...rest, decayRateX32: "0" }).decayRateX32).toBe("0");
    expect(Object.keys(resolveParameters(rest)).sort()).toEqual(Object.keys(base).sort());
    expect(() => resolveParameters({ ...rest, decayRateX32: "1", halfLifeSeconds: "1" })).toThrow();
  });
});
