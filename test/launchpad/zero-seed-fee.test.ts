import { describe, expect, test } from "bun:test";
import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import {
  decayQ128, DECAY_TABLE_Q128, exactInputFee, exactOutputMultiplier, exactOutputPaid, excessHalvingTime, feeAt,
  feeInclusiveDelta, feePercent, MAX_CREATOR_FEE, Q128, Q64,
} from "../../src/launchpad/zero-seed/fee.js";

// fixed_base_duration_v1 (evm-contracts 43d6628) only: its fee math is kept unchanged for reads of launches of that
// model. The tick_rate_v2 math and its creation validation are in zero-seed-tick-rate-fee.test.ts.
// Independent integer vectors for the fixed-base table: fee-decay-vectors.json is generated by the protocol's
// 250-digit Decimal generator (test/vectors/gen-fee-decay-table.py), not by this implementation, and the all-second
// digests come from the interface manifest. Amount rows: the executed high-fee rows of the earlier fee-curve tests;
// computeFee and amountBeforeFee (src/math/fee.sol) are unchanged at 43d6628.
const fixture = (name: string) => {
  const bytes = readFileSync(new URL(`../fixtures/launchpad/${name}`, import.meta.url));
  return { sha256: createHash("sha256").update(bytes).digest("hex"), json: JSON.parse(bytes.toString("utf8")) };
};
const vectors = fixture("zero-seed-fee-decay-vectors.json");
const iface = fixture("zero-seed-interface-43d6628.json").json;
const rows = fixture("zero-seed-fee-curve-rows.json");
const RATES: Record<string, bigint> = Object.fromEntries(Object.entries(iface.fee.rates_q64 as Record<string, string>)
  .map(([key, value]) => [key, BigInt(value)]));
const FINAL = BigInt(iface.fee.final_fee_q64);
const schedule = (initialFee: bigint, feeDuration: bigint, finalFee = FINAL, tradingStart = 1000n) =>
  ({ tradingStart, feeDuration, initialFee, finalFee });

describe("independent vector provenance", () => {
  test("fixtures are the pinned exports", () => {
    expect(vectors.sha256).toBe("7004b29f91540f1b29a568b525d215227565b36d1b490687ae604f5f145b835b");
    expect(rows.sha256).toBe("bf3d3098c9b77befd35166c974793ec1ecdeccaa03adf5cf0b9888c67cac6320");
    expect(iface.manifest_sha256).toBe("6be8bd0a5a54f6dd51f9f7836bd4d64922672deebff7e19a6ff821e318906629");
    expect(iface.fee.max_creator_fee_q64).toBe(MAX_CREATOR_FEE.toString());
    expect(iface.creator_fee_range.max_q64).toBe(MAX_CREATOR_FEE.toString());
    expect(MAX_CREATOR_FEE).toBe(Q64 - 1n);
    expect(iface.fee.half_life_s).toBe(600);
    expect(iface.fee.zero_from_s).toBe(131072);
  });
});

describe("fixed-base decay table parity (bit-exact)", () => {
  test("the table equals both independent exports", () => {
    expect(DECAY_TABLE_Q128.map(String)).toEqual(vectors.json.table_q128);
    expect(DECAY_TABLE_Q128.map(String)).toEqual(iface.fee.table_q128);
    // The contract applies bit 0 as 2^128 minus 0x4baa9be03697a9bc384a821d46c25f.
    expect(Q128 - DECAY_TABLE_Q128[0]).toBe(0x4baa9be03697a9bc384a821d46c25fn);
  });

  test("decay samples, including 600 s = one half and zero from 2^17", () => {
    expect(vectors.json.decay_samples).toHaveLength(14);
    for (const row of vectors.json.decay_samples) expect(decayQ128(BigInt(row.t)).toString()).toBe(row.decay_q128);
    expect(decayQ128(600n)).toBe(Q128 / 2n - 1n);
    expect(decayQ128(131071n)).toBe(0n);
    expect(decayQ128(1n << 40n)).toBe(0n);
    expect(() => decayQ128(-1n)).toThrow("unsigned_domain");
  });

  test("ascending-bit multiply/floor order, not a rounded product", () => {
    let expected = Q128;
    for (const bit of [0, 1, 3]) expected = (expected * DECAY_TABLE_Q128[bit]) / Q128;
    expect(decayQ128(0b1011n)).toBe(expected);
  });

  test("decay is non-increasing over every second of the domain", () => {
    let previous = Q128;
    for (let t = 0n; t <= 131072n; t++) {
      const value = decayQ128(t);
      if (value > previous) throw new Error(`increase at ${t}`);
      previous = value;
    }
    expect(previous).toBe(0n);
  });

  test(`the ${vectors.json.fee_rows.length} independent fee rows`, () => {
    expect(vectors.json.fee_rows).toHaveLength(200);
    for (const row of vectors.json.fee_rows) {
      const s = schedule(BigInt(row.initial), BigInt(row.duration), BigInt(row.final));
      expect(feeAt(s, s.tradingStart + BigInt(row.elapsed)).toString()).toBe(row.fee);
    }
  });

  for (const duration of [600, 3600] as const) {
    for (const [label, initial] of Object.entries(RATES)) {
      test(`every second of D${duration} at ${label}: chained digest, endpoints, bounds, monotone`, () => {
        const s = schedule(initial, BigInt(duration));
        let digest = Buffer.alloc(32);
        let previous = initial;
        for (let t = 0n; t <= BigInt(duration); t++) {
          const fee = feeAt(s, s.tradingStart + t);
          expect(fee <= previous && fee >= FINAL && fee <= initial).toBe(true);
          const word = Buffer.alloc(8);
          word.writeBigUInt64BE(fee);
          digest = createHash("sha256").update(Buffer.concat([digest, word])).digest();
          previous = fee;
        }
        expect(feeAt(s, s.tradingStart)).toBe(initial);
        expect(feeAt(s, s.tradingStart - 1n)).toBe(initial);
        expect(previous).toBe(FINAL);
        expect(digest.toString("hex")).toBe(iface.fee.all_second_digests_sha256[String(duration)][label]);
        if (vectors.json.all_second_digests_sha256[String(duration)]?.[label] !== undefined) {
          expect(digest.toString("hex")).toBe(vectors.json.all_second_digests_sha256[String(duration)][label]);
        }
      });
    }
  }

  test("50% -> 0.3% over 3,600 s halves the excess at the 600 s half-life, rescaled", () => {
    const s = schedule(RATES["50"], 3600n);
    const t = excessHalvingTime(s)!;
    const half = RATES["50"] - FINAL;
    expect(2n * (feeAt(s, s.tradingStart + t) - FINAL)).toBeLessThanOrEqual(half);
    expect(2n * (feeAt(s, s.tradingStart + t - 1n) - FINAL)).toBeGreaterThan(half);
    // (decay(t) - 2^-6) / (1 - 2^-6) = 1/2 at t = 600 * log2(128 / 65) = 586.6 s, so the first such second is 587.
    expect(t).toBe(587n);
    expect(excessHalvingTime(schedule(FINAL, 3600n))).toBeNull();
  });

  test("a one-second window is a cliff to the final fee", () => {
    const s = schedule(RATES["50"], 1n);
    expect(feeAt(s, s.tradingStart)).toBe(RATES["50"]);
    expect(feeAt(s, s.tradingStart + 1n)).toBe(FINAL);
  });

  test("invalid indexed schedules refuse instead of guessing", () => {
    expect(() => feeAt(schedule(RATES["5"], 0n), 2000n)).toThrow("invalid_fee_schedule");
    expect(() => feeAt(schedule(FINAL, 3600n, RATES["5"]), 2000n)).toThrow("invalid_fee_schedule");
    expect(() => feeAt(schedule(Q64, 3600n), 2000n)).toThrow("unsigned_domain");
    expect(() => feeAt(schedule(RATES["5"], 1n << 32n), 2000n)).toThrow("unsigned_domain");
  });
});

describe("amount parity with the executed high-fee rows (both orders, 18/18 and 18/6)", () => {
  const high = rows.json.highRate as Record<string, string & string[]>[];
  const rate = (row: { rate: string }) => RATES[row.rate];
  test("coverage: 50/75/90/99/max x t0/t1 x 18/18, 18/6", () => {
    expect(new Set(high.map((r) => `${r.rate}|${r.order}|${r.dec}`)).size).toBe(20);
  });
  for (const row of high.filter((r) => !r.tags.includes("dust"))) {
    test(row.raw.slice(4), () => {
      const r = rate(row as never);
      const tag = row.tags[0];
      if (tag === "oneUnit" || tag === "buyExactIn") {
        expect(exactInputFee(BigInt(row.gross), r).toString()).toBe(row.fee);
        expect((BigInt(row.gross) - BigInt(row.fee)).toString()).toBe(row.net);
        expect(feeInclusiveDelta({ calculated: -BigInt(row.gross), rate: r, exactOut: false }).withFee.toString()).toBe(`-${row.net}`.replace("-0", "0"));
      } else if (tag === "buyExactOut") {
        expect(exactOutputPaid(BigInt(row.calcQuote), r).toString()).toBe(row.paid);
        expect(feeInclusiveDelta({ calculated: BigInt(row.calcQuote), rate: r, exactOut: true })).toEqual({ fee: BigInt(row.fee), withFee: BigInt(row.paid) });
      } else {
        expect(exactInputFee(BigInt(row.grossQuote), r).toString()).toBe(row.fee);
        expect((BigInt(row.grossQuote) - BigInt(row.fee)).toString()).toBe(row.quoteOut);
      }
    });
  }

  test("helper uint128 and signed int128 limits stay distinct at every rate", () => {
    const bounds = rows.json.bounds;
    expect(bounds).toHaveLength(6);
    for (const row of bounds) {
      const r = RATES[row.rate];
      const helper = BigInt(row.helperLastValid);
      expect(() => exactOutputPaid(helper, r)).not.toThrow();
      expect(() => exactOutputPaid(helper + 1n, r)).toThrow("amount_before_fee_overflow");
      const signed = BigInt(row.signedLastValid);
      expect(() => feeInclusiveDelta({ calculated: signed, rate: r, exactOut: true })).not.toThrow();
      expect(() => feeInclusiveDelta({ calculated: signed + 1n, rate: r, exactOut: true })).toThrow("signed_delta_overflow");
    }
  });

  test("maximum-rate executed signed bound (research-only rate)", () => {
    const row = rows.json.exactOutBounds.find((r: { tags: string[] }) => r.tags.includes("signed"));
    const out = feeInclusiveDelta({ calculated: BigInt(row.calcQuote), rate: Q64 - 1n, exactOut: true });
    expect(out.withFee.toString()).toBe(row.paid);
    expect(() => feeInclusiveDelta({ calculated: BigInt(row.calcQuote) + 1n, rate: Q64 - 1n, exactOut: true })).toThrow("signed_delta_overflow");
  });

  test("exact-output multiplier is nonlinear in the rate", () => {
    expect(exactOutputMultiplier(RATES["5"])).toBe("1.05");
    expect(exactOutputMultiplier(RATES["50"])).toBe("2.00");
    expect(exactOutputMultiplier(RATES["90"])).toBe("9.99");
    expect(exactOutputMultiplier(RATES["99"])).toBe("99.99");
  });
});
